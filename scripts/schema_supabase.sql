-- 1. Tabela Histórico REC (Obras Orçadas e Arquivos .rec)
CREATE TABLE IF NOT EXISTS public.historico_rec (
    numero_obra TEXT PRIMARY KEY,
    dados_json TEXT NOT NULL,
    data_criacao TEXT NOT NULL,
    user_id TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabela Obras (Projetos em edição salvos na tela de Resumo)
CREATE TABLE IF NOT EXISTS public.obras (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL,
    data TEXT NOT NULL,
    dados_json TEXT NOT NULL,
    user_id TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabela Projetos / Concessionárias (Ex: PARAIBA 027, RONDONIA 229)
CREATE TABLE IF NOT EXISTS public.projetos (
    nome TEXT PRIMARY KEY,
    codigo TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

